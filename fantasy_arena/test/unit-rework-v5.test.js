test("성기사 l12 (환생+보호): 보호가 첫 피해를 막고 → 사망 시 환생 → 보호 다시 생김, 두 번째 사망은 제거", () => {
  const { p1 } = setup(g);
  const m = place(g, p1, "l12");
  assert.equal(m.ability, "환생,보호");
  assert.equal(m.text, "환생 · 보호");
  const hp0 = m.hp;
  g.damageMinion(p1, m, 5, {});
  assert.equal(m.hp, hp0, "보호로 막음");
  assert.equal(m.ability, "환생", "보호만 소모, 환생 남음");
  assert.equal(m.text, "환생");
  g.damageMinion(p1, m, 5, {});
  assert.ok(m.dying);
  g.resolveDeath(p1, m);
  assert.ok(p1.board.includes(m), "환생");
  assert.equal(m.hp, 1);
  assert.equal(m.ability, "보호", "인쇄 보호 복원, 환생 소모");
  assert.equal(m.text, "보호");
  g.damageMinion(p1, m, 3, {});
  assert.equal(m.hp, 1, "복원된 보호가 다시 막음");
  g.damageMinion(p1, m, 3, {});
  if (m.dying) g.resolveDeath(p1, m);
  assert.ok(!p1.board.includes(m), "두 번째 사망은 제거");
});

test("블랙드래곤 d27: 4/1/9 · −2/0/0 · 치명+면역", async () => {
  const { p1, p2 } = setup(g);
  const m = place(g, p1, "d27");
  assert.deepEqual([m.atk, m.def, m.hp, m.atkC, m.defC, m.hpC], [4, 1, 9, -2, 0, 0]);
  assert.equal(m.atkSkill, 5);
  assert.ok(g.isImmune(m), "면역");
  assert.equal(m.text, "치명공격 · 면역");
  m.atkC = 0; // 코인 없이 고정 공격
  const foe = place(g, p2, "l20"); foe.ability = null; foe.keywords = []; foe.atkC = 0; foe.defC = 0; foe.hpC = 0; foe.def = 0; foe.hp = 30; foe.maxHp = 30; foe.atk = 0;
  await g.doAttack(p1, m, { kind: "minion", owner: p2, minion: foe }, false);
  assert.ok(!p2.board.includes(foe) || foe.hp <= 0 || foe.dying, "치명: 체력 1 이상 깎으면 즉사");
});

test("툴팁: 모든 유닛의 능력 도움말이 실제 능력(atkSkill·ability)과 일치 (d27 치명+면역, l12 환생+보호)", () => {
  const NAMES = { 2: "관통공격", 3: "돌진공격", 4: "연속공격", 5: "치명공격", 6: "흡혈공격", 7: "약화공격", 8: "석화공격", 9: "광역공격" };
  const KW = ["보호", "환생", "면역", "공격불가"];
  for (const c of CARDS.filter(x => x.type === "minion")) {
    const got = g.collectAbilityTips(g.cloneCard(c.id)).map(x => x.title)
      .filter(t => Object.values(NAMES).includes(t) || KW.includes(t)).sort();
    const want = [];
    if (NAMES[c.atkSkill]) want.push(NAMES[c.atkSkill]);
    String(c.ability || "").split(",").map(s => s.trim()).filter(s => KW.includes(s)).forEach(s => want.push(s));
    assert.deepEqual(got, want.sort(), c.id + " " + c.name);
  }
  assert.deepEqual(g.collectAbilityTips(g.cloneCard("d27")).map(x => x.title), ["치명공격", "면역"]);
  assert.deepEqual(g.collectAbilityTips(g.cloneCard("l12")).map(x => x.title), ["환생", "보호"]);
});
