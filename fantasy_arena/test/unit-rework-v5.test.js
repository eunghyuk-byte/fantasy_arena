test("v5 표 136장: 공/방/체·코인·단순 능력 일치", () => {
  assert.equal(Object.keys(V5).length, 136);
  for (const [id, e] of Object.entries(V5)) {
    const c = byId[id];
    assert.ok(c && c.type === "minion", id);
    assert.deepEqual([c.atk, c.def | 0, c.hp, c.atkC | 0, c.defC | 0, c.hpC | 0], e.slice(0, 6), id + " 수치");
    const want = e[6];
    const parts = want === "—" ? [] : want.split("+");
    if (!parts.every(x => SIMPLE.has(x))) continue; // 소환:/파괴: 등 특수 능력은 기존 그대로
    const got = String(c.ability || "").split(",").map(s => s.trim()).filter(Boolean);
    if (SK[c.atkSkill]) got.push(SK[c.atkSkill]);
    assert.deepEqual(got.sort(), parts.slice().sort(), id + " 능력");
    if (!parts.length) assert.equal(c.text || "", "", id + " 능력 없음 → 문구 없음");
    for (const x of parts) assert.ok(String(c.text).includes(SK[c.atkSkill] === x ? x + "공격" : x), id + " 문구에 " + x);
  }
});

